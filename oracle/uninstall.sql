-- حذف كل كائنات نظام ERP من المخطط الحالي (للتجربة وإعادة التثبيت). **يحذف كل البيانات.**
-- شغّله بحساب المخطط نفسه فقط، وتأكد من اسم المخطط قبل التشغيل:  SELECT USER FROM dual;
SET DEFINE OFF
SET SERVEROUTPUT ON
DECLARE
  PROCEDURE run (p_sql VARCHAR2) IS
  BEGIN EXECUTE IMMEDIATE p_sql; EXCEPTION WHEN OTHERS THEN DBMS_OUTPUT.PUT_LINE('تخطّي: ' || p_sql || ' → ' || SQLERRM); END;
BEGIN
  FOR v IN (SELECT view_name FROM user_views WHERE view_name LIKE 'V\_ERP\_%' ESCAPE '\') LOOP run('DROP VIEW ' || v.view_name); END LOOP;
  run('DROP PACKAGE erp_quote');
  run('DROP PACKAGE erp_po');
  run('DROP PACKAGE erp_pos');
  run('DROP PACKAGE erp_period');
  run('DROP PACKAGE erp_fin');
  run('DROP PACKAGE erp_payroll');
  run('DROP PACKAGE erp_hr');
  run('DROP PACKAGE erp_asset');
  run('DROP PACKAGE erp_trade');
  run('DROP PACKAGE erp_inventory');
  run('DROP PACKAGE erp_gl');
  FOR t IN (SELECT table_name FROM user_tables WHERE table_name IN (
      'ERP_QUOTE_LINES','ERP_QUOTATIONS','ERP_PO_RECEIPT_LINES','ERP_PO_RECEIPTS','ERP_PO_LINES','ERP_PURCHASE_ORDERS','ERP_SETTINGS','ERP_POS_PAYMENTS','ERP_POS_SALE_LINES','ERP_POS_SALES','ERP_POS_SHIFTS','ERP_POS_REGISTERS','ERP_YEAR_CLOSINGS','ERP_PERIODS','ERP_PAYROLL_ITEMS','ERP_PAYROLL_LINES','ERP_PAY_ADJUSTMENTS','ERP_ADVANCES','ERP_PAYROLL_RUNS','ERP_EMP_COMPONENTS',
      'ERP_PAY_COMPONENTS','ERP_SALARY_HISTORY','ERP_EMPLOYEES','ERP_DEPARTMENTS','ERP_DEPRECIATION','ERP_DEP_RUNS','ERP_ASSETS','ERP_ASSET_CATEGORIES',
      'ERP_PAYMENTS','ERP_INVOICE_LINES','ERP_INVOICES','ERP_COUNTERS','ERP_PARTIES',
      'ERP_STOCK_MOVES','ERP_STOCK','ERP_ITEMS','ERP_WAREHOUSES','ERP_LINES','ERP_ENTRIES','ERP_ACCOUNTS')
    ORDER BY CASE table_name
      WHEN 'ERP_QUOTE_LINES' THEN 1 WHEN 'ERP_QUOTATIONS' THEN 2 WHEN 'ERP_PO_RECEIPT_LINES' THEN 3 WHEN 'ERP_PO_RECEIPTS' THEN 4 WHEN 'ERP_PO_LINES' THEN 5 WHEN 'ERP_PURCHASE_ORDERS' THEN 6 WHEN 'ERP_SETTINGS' THEN 7 WHEN 'ERP_POS_PAYMENTS' THEN 8 WHEN 'ERP_POS_SALE_LINES' THEN 9 WHEN 'ERP_POS_SALES' THEN 10 WHEN 'ERP_POS_SHIFTS' THEN 11 WHEN 'ERP_POS_REGISTERS' THEN 12 WHEN 'ERP_YEAR_CLOSINGS' THEN 13 WHEN 'ERP_PERIODS' THEN 14 WHEN 'ERP_PAYROLL_ITEMS' THEN 15 WHEN 'ERP_PAYROLL_LINES' THEN 16 WHEN 'ERP_PAY_ADJUSTMENTS' THEN 17 WHEN 'ERP_ADVANCES' THEN 18 WHEN 'ERP_PAYROLL_RUNS' THEN 19 WHEN 'ERP_EMP_COMPONENTS' THEN 20 WHEN 'ERP_PAY_COMPONENTS' THEN 21 WHEN 'ERP_SALARY_HISTORY' THEN 22 WHEN 'ERP_EMPLOYEES' THEN 23 WHEN 'ERP_DEPARTMENTS' THEN 24 WHEN 'ERP_DEPRECIATION' THEN 25 WHEN 'ERP_DEP_RUNS' THEN 26 WHEN 'ERP_ASSETS' THEN 27 WHEN 'ERP_ASSET_CATEGORIES' THEN 28 WHEN 'ERP_PAYMENTS' THEN 29 WHEN 'ERP_INVOICE_LINES' THEN 30 WHEN 'ERP_INVOICES' THEN 31 WHEN 'ERP_COUNTERS' THEN 32 WHEN 'ERP_PARTIES' THEN 33 WHEN 'ERP_STOCK_MOVES' THEN 34 WHEN 'ERP_STOCK' THEN 35 WHEN 'ERP_ITEMS' THEN 36 WHEN 'ERP_WAREHOUSES' THEN 37 WHEN 'ERP_LINES' THEN 38 WHEN 'ERP_ENTRIES' THEN 39 WHEN 'ERP_ACCOUNTS' THEN 40 ELSE 41 END) LOOP
    run('DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE');
  END LOOP;
  run('DROP SEQUENCE erp_stock_doc_seq');
  run('DROP TYPE erp_quote_line_tab');
  run('DROP TYPE erp_quote_line_t');
  run('DROP TYPE erp_po_rcv_tab');
  run('DROP TYPE erp_po_rcv_t');
  run('DROP TYPE erp_po_line_tab');
  run('DROP TYPE erp_po_line_t');
  run('DROP TYPE erp_pos_ret_tab');
  run('DROP TYPE erp_pos_ret_t');
  run('DROP TYPE erp_pos_pay_tab');
  run('DROP TYPE erp_pos_pay_t');
  run('DROP TYPE erp_pos_line_tab');
  run('DROP TYPE erp_pos_line_t');
  run('DROP TYPE erp_msg_tab');
  run('DROP TYPE erp_inv_line_tab');
  run('DROP TYPE erp_inv_line_t');
  run('DROP TYPE erp_line_tab');
  run('DROP TYPE erp_line_t');
  DBMS_OUTPUT.PUT_LINE('تم الحذف.');
END;
/
